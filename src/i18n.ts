const dictionaries = { en, ru };

function initialLocale(): Locale {
  const saved = localStorage.getItem("apoj-locale");
  if (saved === "en" || saved === "ru") return saved;
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

const i18n = createRoot(() => {
  const [locale, setLocaleSignal] = createSignal<Locale>(initialLocale());
  const dictionary = createMemo(() => flatten(dictionaries[locale()]));
  const t = translator(dictionary, resolveTemplate);
  return { locale, setLocaleSignal, t };
});

export const locale = i18n.locale;
export const t = i18n.t;

export function setLocale(next: Locale) {
  i18n.setLocaleSignal(next);
  localStorage.setItem("apoj-locale", next);
  document.documentElement.lang = next;
}

document.documentElement.lang = locale();
